"""data.yaml writer for Ultralytics YOLO.

We avoid a YAML library dependency for this small file. The format is
strict enough that we can emit it deterministically.
"""
from __future__ import annotations

from pathlib import Path


def _yaml_str(s: str) -> str:
    """Quote a class name if it contains anything YAML might mis-parse."""
    if not s:
        return "''"
    if any(c in s for c in " :#-?,&*!|>'\"%@`"):
        return "'" + s.replace("'", "''") + "'"
    return s


def write_data_yaml(
    *,
    output_dir: Path,
    classes: list[str],
    has_test: bool = True,
) -> Path:
    """Write {output_dir}/data.yaml in Ultralytics format. Returns the path.

    Layout assumed (created by the converter):
        {output_dir}/images/{train,val,test}/
        {output_dir}/labels/{train,val,test}/
    """
    names = "[" + ", ".join(_yaml_str(c) for c in classes) + "]"
    lines: list[str] = [
        "# Auto-generated by AI Auto Training Platform",
        f"path: {output_dir.as_posix()}",
        "train: images/train",
        "val: images/val",
    ]
    if has_test:
        lines.append("test: images/test")
    lines.append(f"nc: {len(classes)}")
    lines.append(f"names: {names}")
    yaml = "\n".join(lines) + "\n"

    out = output_dir / "data.yaml"
    out.write_text(yaml, encoding="utf-8")
    return out
